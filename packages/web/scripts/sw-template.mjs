/** THE SERVICE WORKER, AS A TEMPLATE, because a hand-written one cannot name the shell it has to
 *  precache: Vite content-hashes its output (`index-B_kCz-LY.js`), so the list only exists after a
 *  build. `assemble-deploy.mjs` fills it in and writes the result to `dist/sw.js`; nothing ships a
 *  service worker in dev, where it would only serve yesterday's bundle over the dev server.
 *
 *  Exported as a function rather than a file so a test can read the output without running a build.
 */
export function serviceWorkerSource({ version, shell }) {
  return `// GENERATED by packages/web/scripts/assemble-deploy.mjs — edit sw-template.mjs instead.
const SHELL_CACHE = ${JSON.stringify(`edh-seer-shell-${version}`)};
const SHELL = ${JSON.stringify(shell)};

// THE THREE ROUTES THIS WORKER HAS AN OPINION ABOUT, and it has none about anything else. Scryfall
// card art is cross-origin and already cached by the app itself (\`art-loader.ts\`); passing it
// through untouched keeps one cache policy per thing rather than two disagreeing ones.
const isShell = (url) => url.origin === self.location.origin
  && (url.pathname === "/" || SHELL.includes(url.pathname));
// Content-addressed by the build: \`/static/v-<hash>/\` and \`/assets/index-<hash>.js\` both change
// their URL whenever their bytes change, which is exactly the condition that makes cache-first
// correct rather than a staleness bug. Before the version directory existed, a card shard kept its
// name across corpus rebuilds and this rule would have frozen a reader on old oracle text.
const isImmutable = (url) => url.origin === self.location.origin
  && (url.pathname.startsWith("/static/v-") || url.pathname.startsWith("/assets/"));
// The one file that is not content-addressed: it names the version everything else hangs off.
const isManifest = (url) => url.origin === self.location.origin
  && url.pathname === "/static/manifest.json";

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await cache.addAll([...SHELL, "/"]);
    // SAFE HERE, AND ONLY BECAUSE THE APP IS ONE CHUNK. Skipping the wait swaps the worker under a
    // running page, which breaks an app that lazily imports chunks the old build named. This build
    // emits a single JS bundle (the build's own size warning says so), so a live page has already
    // loaded everything it will ever ask for. Revisit this line if code splitting is turned on.
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      // Only this worker's own shells. The card caches are versioned and evicted by the app
      // itself, and \`mtg-art-v1\` belongs to the art loader.
      if (name.startsWith("edh-seer-shell-") && name !== SHELL_CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);

  if (isImmutable(url)) {
    event.respondWith((async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      const res = await fetch(request);
      if (res.ok) (await caches.open(SHELL_CACHE)).put(request, res.clone());
      return res;
    })());
    return;
  }

  // NETWORK FIRST for the two things that must be current: the shell, so a deploy is picked up on
  // the next load rather than whenever a cache expires, and the manifest, because it is the only
  // pointer to which artifacts are live. Cache is the OFFLINE answer for both, not the fast one.
  if (isShell(url) || isManifest(url)) {
    event.respondWith((async () => {
      try {
        const res = await fetch(request);
        if (res.ok) (await caches.open(SHELL_CACHE)).put(request, res.clone());
        return res;
      } catch (err) {
        const cached = await caches.match(request) ?? await caches.match("/");
        if (cached) return cached;
        throw err;
      }
    })());
  }
});
`;
}
