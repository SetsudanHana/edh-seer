import type { CardTags } from "@edh-seer/tagger";
import type { DeckCard } from "./types.js";
import real from "./fixtures/removal-derived.json" with { type: "json" };
import voltronReal from "./fixtures/voltron-derived.json" with { type: "json" };

type Real = { oracleText: string; typeLine: string; manaValue: number; abilities: CardTags["abilities"] };
const REAL = real as unknown as Record<string, Real>;

/** A DeckCard carrying a REAL card's Mongo oracle text and its REAL derived abilities (`cardTagsDerived`, derive 350), so a role rule that reads derived data is tested on what
 *  derive actually writes. The fixture is `fixtures/removal-derived.json`, generated by reading both collections; never hand-edit it. */
export function realCard(name: string, over: { oracleText?: string; extraAbilities?: CardTags["abilities"] } = {}): DeckCard {
  const r = REAL[name];
  if (r === undefined) throw new Error(`removal-derived.json has no card "${name}"`);
  return {
    card: { name, typeLine: r.typeLine, oracleText: over.oracleText ?? r.oracleText, keywords: [], colors: [], manaValue: r.manaValue } as never,
    tags: {
      oracleId: name, schemaVersion: 1, promptVersion: 1, model: "t",
      characteristics: { types: [r.typeLine.toLowerCase()], subtypes: [], colors: [], identity: [], cmc: r.manaValue, power: null, toughness: null, token: false, keywords: [] },
      abilities: [...r.abilities, ...(over.extraAbilities ?? [])],
    } as never,
  };
}

/** The same real card under another name (a deck of ten Murders needs ten names). */
export const renamed = (name: string, as: string): DeckCard => ({ ...realCard(name), card: { ...realCard(name).card, name: as } });

type Voltron = { oracleText: string; typeLine: string; manaValue: number; keywords: string[]; characteristics: NonNullable<CardTags["characteristics"]>; abilities: CardTags["abilities"] };
const VOLTRON = voltronReal as unknown as Record<string, Voltron>;

/** Like `realCard`, but with the card's REAL derived `characteristics` (subtypes, `enchants`) and Scryfall `keywords` as well: for a role that reads the Enchant line or a printed keyword
 *  (`wincon.voltron`, #1315). Fixture `fixtures/voltron-derived.json`, generated by reading `cards` and `cardTagsDerived` at derive 372; never hand-edit it. */
export function realAura(name: string): DeckCard {
  const r = VOLTRON[name];
  if (r === undefined) throw new Error(`voltron-derived.json has no card "${name}"`);
  return {
    card: { name, typeLine: r.typeLine, oracleText: r.oracleText, keywords: r.keywords, colors: [], manaValue: r.manaValue } as never,
    tags: { oracleId: name, schemaVersion: 1, promptVersion: 1, model: "t", characteristics: r.characteristics, abilities: r.abilities } as never,
  };
}
